#include <stdio.h>

/*
    Претоварване на функции - Function overloading

    В C по подразбиране няма възможност да дефинираме няколко функции с едно и също име,
    но с различни параметри и логика.
*/

#if 0   // С  #if 0 изключвам парчето от компилация

void foo(int a)
{
    printf("%d\n", a);
}

void foo(float a)       // Компилационна грешка: conflicting types for 'foo'
{
    printf("%f\n", a);
}

#endif

/*
    Горният код няма да се компилира, защото двете функции имат едно и също име.

    В C++ този проблем е решен чрез name mangling (декориране на имена): компилаторът
    сам добавя към името на функцията информация за типовете на параметрите ѝ.
    Така на ниско ниво функциите вече имат различни имена.

    Например в C++ (компилатор g++):

        int   sum(int a, int b);        --> става _Z3sumi   (i = int)
        float sum(float a, float b);    --> става _Z3sumf   (f = float)

    В C можем да постигнем подобен ефект, но РЪЧНО:
        1) даваме на всяка функция уникално име (ръчно "декориране")
        2) с макроса _Generic (от C11) избираме правилната функция според типа на аргумента

    Изборът става по време на КОМПИЛАЦИЯ, така че няма загуба на производителност.
    Недостатъкът е, че трябва да пишем повече код и всеки нов тип трябва да се добави ръчно.
*/

void foo_i(int a)    { printf("int:    %d\n", a); }
void foo_f(float a)  { printf("float:  %f\n", a); }
void foo_d(double a) { printf("double: %f\n", a); }

// 2) _Generic избира името на функцията според типа на x, след което я извикваме с подадения аргумент (x)
#define foo(x) _Generic((x),    \
    int:    foo_i,              \
    float:  foo_f,              \
    double: foo_d               \
)(x)

int main(void)
{
    foo(42);      // int    --> foo_i(42)
    foo(3.14f);   // float  --> foo_f(3.14f)
    foo(3.14);    // double --> foo_d(3.14)

    return 0;
}
