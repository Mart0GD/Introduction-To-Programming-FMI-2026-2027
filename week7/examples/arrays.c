#include <stdio.h>

/*
    ===========================================================
    проверка на размера по време на компилация чрез "static" в параметрите на функция
    ===========================================================

    Ключовата дума "static" в декларацията на параметър на функция
    (възможност от C99) казва на компилатора:

        "Извикващият трябва да подаде масив с ПОНЕ толкова елемента."

    Това НЕ Е проверка по време на изпълнение.
    То НЕ заделя никаква памет.

    Ако извикващият подаде по-малък масив → недефинирано поведение (Undefined Behavior),
    но много компилатори могат да предупредят за това при високо ниво на предупреждения.
*/

// *гаранция* (не принудително налагане) по време на компилация за минималната дължина на масива
void foo(int arr[static 100]);


/*
    ===========================================================
    ВАЖНО: това НЕ създава и НЕ очаква масив от 1024 елемента
    ===========================================================

    В параметрите на функция масивите ВИНАГИ се превръщат (decay) в указатели.
    Така че:

        void foo2(int arr[1024]);

    е АБСОЛЮТНО същото като:

        void foo2(int *arr);

    Числото "1024" служи само като документация и се игнорира
    от компилатора по отношение на типа.
*/
void foo2(int arr[1024]) {

    /*
        ===========================================================
        sizeof(arr), когато 'arr' е параметър на функция
        ===========================================================

        Вътре във функцията 'arr' е указател. Винаги.
        Така че:

            sizeof(arr)       -> sizeof(int*)   (8 байта на 64-битова система)
            sizeof(arr[0])    -> sizeof(int)    (4 байта)

        Следователно изчислената "дължина" става:

            8 / 4 = 2

        което е ГРЕШНО, защото информацията за размера на масива е загубена.
    */
    int len = sizeof(arr) / sizeof(arr[0]); // ВИНАГИ 2 на 64-битова система
}


int main() {

    const int a = 10;   // локална константа → валиден размер за VLA (C99+)
    int var = 10;       // стойност по време на изпълнение → също валиден размер за VLA (C99+)

    #define SIZE 10     // макрос → константа по време на компилация

    // ---------------------------
    // Деклариране на масиви
    // ---------------------------

    int arr1[a];        // VLA — масив с размер, определен по време на изпълнение
    int arr2[SIZE];     // масив с размер, определен по време на компилация
    int arr3[10];       // масив с размер, определен по време на компилация
    int arr4[var];      // VLA — НЕ Е позволено в C90

    /*
        ===========================================================
        Масиви, инициализирани с нули
        ===========================================================

        Изричното задаване на инициализатор води до това масивът
        да бъде инициализиран с нули.

        Тези два реда са еквивалентни:
    */
    int zero_init1[SIZE] = {0};                     // всички елементи = 0
    int zero_init2[SIZE] = {[0 ... SIZE - 1] = 0};  // разширение на GCC: всички = 0

    /*
        ===========================================================
        Неинициализирани масиви
        ===========================================================

        Те съдържат неопределени ("garbage") стойности.
        Локалната автоматична памет НЕ се нулира от компилатора.
    */
    int trash1[SIZE] = {};   // НЕ се инициализира с нули в C — разширение на GCC → неинициализиран
    int trash2[SIZE];        // неинициализиран 

    /*
        ===========================================================
        sizeof() работи САМО за масиви В ТЯХНАТА СОБСТВЕНА ОБЛАСТ НА ВИДИМОСТ
        ===========================================================

        Тук arr1 е ИСТИНСКИ масив и е в областта на видимост, така че имаме достъп до цялата информация
    */
    int len = sizeof(arr1) / sizeof(arr1[0]);  // правилна дължина

    /*
        ===========================================================
        ЗАПОМНЕТЕ:
        -----------------------------------------------------------
        Ако подадете arr1 на функция:

            foo2(arr1);

        вътре във foo2() sizeof() ВЕЧЕ НЕ РАБОТИ, защото масивът
        се превръща в указател и информацията за размера се губи.
        ===========================================================
    */

    return 0;
}
