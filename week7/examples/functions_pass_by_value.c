#include <stdio.h>

/*
*    ===========================================================
*    Подаване по стойност
*    ===========================================================
*
*    При извикване стойността на аргумента се КОПИРА в параметъра
*    'elem', който живее в стековата рамка на тази функция.
*
*    'elem' тук и 'elem' в main() са ДВЕ РАЗЛИЧНИ променливи
*    с различни адреси, които просто имат еднакво име.
*
*    Всички промени се извършват върху копието и изчезват,
*    когато функцията приключи и рамката ѝ бъде освободена.
*/
void add_one_if_even_by_value(int elem)
{
    printf("  [by_value]   адрес на elem: %p\n", (void *)&elem);

    if (elem % 2 == 0)
    {
        elem++;   // променяме КОПИЕТО, оригиналът остава същият
    }
}

/*
*    ===========================================================
*    Подаване по адрес
*    ===========================================================
*
*    Функцията получава АДРЕСА на оригиналната променлива.
*    Самият указател 'elem' отново е копие (в C всичко се подава
*    по стойност), но копието съдържа същия адрес, затова сочи
*    към оригинала.
*
*    Чрез разименуване (*elem) четем и променяме стойността,
*    която се намира в стековата рамка на main().
*
*    Скобите в (*elem)++ са задължителни:
*        *elem++   -> увеличава УКАЗАТЕЛЯ (++ е с по-висок приоритет)
*        (*elem)++ -> увеличава СТОЙНОСТТА, към която сочи
*/
void add_one_if_even_by_address(int *elem)
{
    printf("  [by_address] адрес в elem:  %p\n", (void *)elem);

    if (*elem % 2 == 0)
    {
        (*elem)++;   // променяме ОРИГИНАЛА чрез указателя
    }
}

/*
*    ===========================================================
*    Размяна по стойност (НЕ РАБОТИ)
*    ===========================================================
*
*    'a' и 'b' са копия на стойностите на x и y.
*    Разменяме копията, а x и y в main() остават непроменени.
*/
void swap_by_value(int a, int b)
{
    int tmp = a;
    a = b;
    b = tmp;      // разменят се само копията
}

/*
*    ===========================================================
*    Размяна по адрес (РАБОТИ)
*    ===========================================================
*
*    Подават се копия на АДРЕСИТЕ на оригиналните променливи.
*    'a' сочи към x, 'b' сочи към y.
*
*    Стъпки (при x = 1, y = 2):
*        tmp = *a;   -> tmp = 1        (запазваме стойността на x)
*        *a  = *b;   -> x   = 2        (записваме y в x)
*        *b  = tmp;  -> y   = 1        (записваме старото x в y)
*
*    Без 'tmp' стойността на x би се загубила след втората стъпка.
*/
void swap_by_address(int *a, int *b)
{
    int tmp = *a;
    *a = *b;
    *b = tmp;     // разменят се оригиналите
}

int main(void)
{
    // ------------------------------------------------------
    //              add_one_if_even
    // ------------------------------------------------------

    int elem = 2;
    printf("[main]         адрес на elem: %p\n", (void *)&elem);

    // Подаваме СТОЙНОСТТА 2. Функцията работи с копие.
    add_one_if_even_by_value(elem);
    printf("След by_value:   elem = %d\n", elem);   // 2 - без промяна

    // Подаваме АДРЕСА на elem. Функцията работи с оригинала.
    add_one_if_even_by_address(&elem);
    printf("След by_address: elem = %d\n", elem);   // 3

    /*
        Обърнете внимание на отпечатаните адреси:
          - адресът в by_value е РАЗЛИЧЕН от този в main (копие);
          - адресът в by_address СЪВПАДА с този в main (оригинал).
    */

    // ------------------------------------------------------
    //                     swap
    // ------------------------------------------------------

    int x = 1;
    int y = 2;

    swap_by_value(x, y);
    printf("След swap_by_value:   x = %d, y = %d\n", x, y);   // x = 1, y = 2

    swap_by_address(&x, &y);
    printf("След swap_by_address: x = %d, y = %d\n", x, y);   // x = 2, y = 1

    return 0;
}
