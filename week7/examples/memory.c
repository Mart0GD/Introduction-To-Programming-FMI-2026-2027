// ===============================
// Памет, инициализирана с нули, в C
// ===============================

// Глобалните и статичните променливи имат *статична продължителност на съхранение*
// (static storage duration).
// Според стандарта на C, ако НЕ ги инициализирате изрично,
// те автоматично се инициализират с нула (или NULL за указатели).
// Това се случва *преди да започне main()*, обикновено по време на стартирането на програмата.

// ЗАЩО? Защото:
// 1. Те се поставят в секцията .bss на програмата.
// 2. Зареждащата програма (loader) или кодът за инициализация нулира .bss за ефективност.
// 3. Така големите неинициализирани променливи не заемат място в изпълнимия файл.

// Пример: глобална const променлива (пак има статична продължителност на съхранение!)
const int some_size;   // Инициализира се с 0, защото е глобална.

// Статичните масиви без изрична инициализация също отиват в .bss,
// ОСВЕН ако ги инициализирате — тогава отиват в .data.
int arr[50];           // Всичките 50 елемента автоматично са 0.

// --------------------------------------------------------------
// Невалидно!!!!
// int arr[some_size]
// --------------------------------------------------------------
// Това е невалидно, защото "some_size" НЕ Е константа по време на компилация.
// Въпреки че е 'const', глобалните const променливи в C заемат памет,
// затова не могат да се използват като размер на статични масиви.

// Само истински константи по време на компилация, като:
//   #define SIZE 10
//   целочислени литерали, могат да се използват за размер на глобални масиви.


// ===============================
// Автоматична (стекова) памет в C
// ===============================
int main(){

    // Локалните (автоматични) променливи НЕ се нулират.
    int some_size;  // Съдържа произволни стойности — НЕ Е инициализирана с нула!

    // Автоматичните масиви също започват с произволни стойности, освен ако не са изрично инициализирани:
    // int a[10];  // <- запълнен със случайно съдържание от стека

    // Защо? Защото:
    // 1. Нулирането на стековите променливи всеки път би забавило изпълнението.
    // 2. Езикът C е проектиран за производителност, а не за безопасност.

    return 0;
}
