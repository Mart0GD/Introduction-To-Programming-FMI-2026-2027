#include <stdio.h>

void foo(int *arr) {
    /*
        Тук получаваме копие на указателя към първия елемент на масива.
        Все още имаме достъп до данните и можем да ги променяме, но не можем
        да променим самия *тип* на масива (информацията за размера е загубена).
    */

    printf("First element: %d\n", *arr);
}

void foo_direct(int (*arr)[5]) {
    /*
        Тук получаваме указател към целия масив (тип: int (*)[5]).
        Така се запазва информацията за размера на масива.
    */

    printf("Size of array: %d\n", sizeof(*arr) / sizeof(*(arr[0])));
}

