
int main()
{
    // целочислени типове
    short x = 5;                            // >= 2 байта, обикновено 2 [-32 768 ; 32 767]
    int y = 10;                             // >= 2 байта, обикновено 4 [-2 147 483 648 ; 2 147 483 647]
    long z = 100000;                        // >= 4 байта: 8 при LP64 (Linux/macOS), 4 при LLP64 (Windows)
    long long k = 100000000000;             // >= 8 байта, обикновено 8 [-2^63 ; 2^63 - 1]

    // беззнакови целочислени типове
    unsigned short ux = 5;                  // >= 2 байта, обикновено 2 [0 ; 65 535]
    unsigned int uy = 10;                   // >= 2 байта, обикновено 4 [0 ; 4 294 967 295]
    unsigned long uz = 100000;              // >= 4 байта: 8 при LP64, 4 при LLP64
    unsigned long long uk = 100000000000;   // >= 8 байта, обикновено 8 [0 ; 2^64 - 1]

    // типове с плаваща запетая
    float f = 5.5f;                         // обикновено 4 байта, 23 мантиса, 8 експонента, 1 знак
    double d = 10.99;                       // обикновено 8 байта, 52 мантиса, 11 експонента, 1 знак
    long double ld = -100.9999;             // x86-64 Linux: 16 байта (80-битов формат); MSVC: 8 байта

    // символен тип
    char c = 'A';                           // 1 байт; знакът зависи от платформата (x86 е signed, ARM е unsigned)
    unsigned char uc = 'A';                 // 1 байт [0 ; 255]

    // преди C99 няма булев тип (C99 добавя _Bool и <stdbool.h>)
    int false = 0;                          // лъжа
    int true  = 1;                          // истина е всяка стойност, различна от 0

    return 0;
}