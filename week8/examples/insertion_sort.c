#include <stdio.h>
#define SIZE 10

/*
    Единственият полезен алгоритъм от така наречените "интуитивни" сортиращи алгоритми, които чуим.
    Идеята е, че на мсяка стъпка елементът се мърда докато не срещне по-малък или не стане първи в масива.

    Най-лошият случай тук отново е n * n (когато масивът е обърнат), защото трябва за всеки елемент да
    го разменим с всички не сортирани все още!
*/

int main(void)
{
    int arr[SIZE] = {1,-2,3,2,4,11,8,5,22,-100};

    for(int i = 1; i < SIZE; ++i)
    {
        // Запазваме позицията
        int pos = i;

        // Запазваме елемента
        int elem = arr[i];

        // Преместваме елементите докато не видим по-малък
        while(pos > 0 && elem < arr[pos - 1])
        {
            // За да не правим постоянни размени, които са скъпи просто shift-ваме елементите на дясно
            arr[pos] = arr[pos - 1];
            pos--;
        }
        
        // Задаваме стойността на елемента на новото му сортирано място
        arr[pos] = elem;
    }

    return 0;
}    
