#include <stdio.h>
#define SIZE 10

/*
    Сортиране с пряката селекция е може би най-интуитивния метод за сортиране.
    На всяка стъпка намираме най-малкия елемент и го поставяме на съответната му позиця.

    При всеки случай извършваме n * n сравнения.
    Освен това този алгоритъм не е стабилен, което значи че не запазва реда на срещане
    на еднаквите елементи в масива!
*/

int main(void)
{
    int arr[SIZE] = {23,1,-2,-4,11,12,112,94,23,12};

    for(int i = 0; i < SIZE; ++i)
    {
        // Избираме най-малкия елемент
        int min = i;
        for(int j = i + 1; j < SIZE; ++j)
        {
            if(arr[j] < arr[min]) min = j;
        }

        // Разменяме
        int temp = arr[i];
        arr[i] = arr[min];
        arr[min] = temp;
    }

    return 0;
}    
