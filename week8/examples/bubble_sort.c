#include <stdio.h>

/*
    Много популярен, но изцяло безполезен поради бавнодействието си метод за сортиране.        
    Идеята е, че на всяка стъпка "i" най-тежкия елемент в arr [0..n - 1 - i] ще отиде на позия "n - 1 - i"
    
    В най-лошия случай ще извършим n * n стъпки (масива е обърнат), тогава за всеки елемент ще го разменим с всеки друг!
*/

int main(){

    int arr[] = {10, 1 , 12 , 3 , 123, 1, 87, 13, 68};
    int len = sizeof(arr) / sizeof(arr[0]);

    int swapped, temp;
    for (int i = 0; i < len; i++)
    {
        // Показва ни дали масивът вече не е сортиран
        swapped = 0;
        
        for (int j = 0; j < len - i - 1; ++j)
        {
            // елементът си е на мястото
            if(arr[j] <= arr[j + 1]) continue;

            // Размяна
            temp = arr[j];
            arr[j] = arr[j + 1];
            arr[j + 1] = temp;
            swapped = 1;
        }

        // Ако няма размяна значи е сортиран!
        if(!swapped) break;
    }
    
    return 0;
}
