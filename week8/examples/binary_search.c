int binary_search(int arr[], int size, int desired);

/*
    Един от най-важните алгоритми за всички времена
    Работи единствено над сортирана селекция от елементи и намира индекса на желания елемент в масива, ако съществува!

    Скоростта му на работта в най-лошия случай (елементите са в краищата) се изразява с функцията : log(n),
    където n е размера на масива!

    Извод: намираме индекса на елемент за най-много log(n) стъпки!
*/

int main(){

    // Задължително сортиран масив!
    int arr[] = {1, 2, 7, 11, 23, 43, 23, 87, 112, 132};
    int len = sizeof(arr) / sizeof(arr[0]);

    printf("%d\n", binary_search(arr, len, 11));
    return 0;
}

int binary_search(int arr[], int size, int desired){

    int l = 0;
    int r = size - 1;
    int m;
    
    while (l <= r)
    {
        // намираме новата среда 
        m = l + (r - l) / 2;
        
        if (arr[m] > desired)        r = m;     //> Елементът е в ляво от средата, затова снишаваме дясната част
        else if(arr[m] < desired)    l = m + 1; //> Елементът е в дясно от средата, затова снишаваме лявата страна 
        else return m;                          //> Това е елемента 
    }

    // Не намерихме елемента
    return -1;
}
